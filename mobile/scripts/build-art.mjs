// Bundles every art/<id>.svg into src/characters/artData.ts so the app can render them with SvgXml.
// Run: npm run art
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'art');
const entries = readdirSync(dir)
  .filter((f) => f.endsWith('.svg'))
  .sort()
  .map((f) => {
    const id = f.replace(/\.svg$/, '');
    const xml = readFileSync(join(dir, f), 'utf8')
      .replace(/<!--[\s\S]*?-->/g, '')
      .replace(/\s*\n\s*/g, ' ')
      .trim();
    return `  ${JSON.stringify(id)}: ${JSON.stringify(xml)},`;
  });
writeFileSync(
  join(root, 'src/characters/artData.ts'),
  `// Generated by scripts/build-art.mjs from art/*.svg. Do not edit by hand.\nexport const ART: Record<string, string> = {\n${entries.join('\n')}\n};\n`,
);
console.log(`Bundled ${entries.length} characters.`);
